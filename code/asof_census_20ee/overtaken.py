def git(*args):
    got = subprocess.run(["git", "-C", ROOT, *args], capture_output=True)
    if got.returncode != 0:
        raise SystemExit("overtaken: git %s failed: %s"
                         % (" ".join(args),
                            got.stderr.decode("utf-8", "replace").strip()))
    return got.stdout.decode("utf-8", "surrogateescape")


def blob(rev, path):
    """The bytes of `path` at `rev`, or None when it is not in that tree."""
    got = subprocess.run(["git", "-C", ROOT, "show", "%s:%s" % (rev, path)],
                         capture_output=True)
    if got.returncode != 0:
        return None
    return got.stdout.decode("utf-8", "surrogateescape")


def last_touch(rev):
    """path -> how many commits back from `rev` it was last written.

    ONE `git log` WALK AND NOT ONE PER PATH.  884 pairs is 1768 `git log -1`
    calls the obvious way; this is one call and a dict, and it is also the
    honest spelling -- every path's answer comes out of the same walk, so no
    two figures on this page can be taken against different histories.

    LOWER IS NEWER.  The index is a position in the walk and NOT a timestamp:
    a rebase rewrites dates, and this estate's refinery rebases every branch.
    """
    out, idx = {}, -1
    for line in git("log", "--format=%H", "--name-only", rev).splitlines():
        if not line:
            continue
        if len(line) == 40 and all(c in "0123456789abcdef" for c in line):
            idx += 1
            continue
        out.setdefault(line, idx)
    return out


def widen(missed, tracked):
    """(transcript, producer) for transcripts the strict convention misses.

    `code/D/out_X_Y.txt` is offered to `code/D/X_Y.py|sh`, then to `code/D/X.py`
    and so on, stripping ONE trailing `_`-separated segment at a time and
    stopping at the first producer that exists.  SAME DIRECTORY ONLY, which is
    the guard the one false pair defeats anyway -- a foreign transcript copied
    in carries no mark a basename rule can read.
    """
    got = []
    for path in sorted(missed):
        here = os.path.dirname(path)
        stem = os.path.basename(path)[4:-4]
        hit = None
        while "_" in stem and hit is None:
            stem = stem.rsplit("_", 1)[0]
            for ext in (".py", ".sh"):
                cand = os.path.join(here, stem + ext)
                if cand in tracked:
                    hit = cand
                    break
        if hit:
            got.append((path, hit))
    return got


def is_archival(transcript):
    """True when the FILENAME says this transcript preserves a past state."""
    segs = _SEG.split(os.path.basename(transcript)[4:-4])
    return any(tok in segs for tok in ARCHIVAL_TOKENS)


def code_signature(src, path):
    """`src` with its prose gone, as a comparable sequence of code lines.

    pinnable.code_only BLANKS prose and PRESERVES COLUMNS, so its output still
    differs when a comment merely changes length; the sequence of non-blank
    stripped lines is what survives a prose-only edit and nothing else.  The
    separator is imported: this arm cannot disagree with permuted.py section 4
    about what prose is.
    """
    blanked, separated = pinnable.code_only(src, path)
    return (tuple(l.strip() for l in blanked.splitlines() if l.strip()),
            separated)


def literals(src):
    """Every long single-line string literal in `src`; EMPTY if it will not parse.

    An unparseable producer therefore contributes NO witness rather than a
    misleading one, which is the weakening direction section 4 declares.
    """
    try:
        tree = ast.parse(src)
    except (SyntaxError, ValueError):
        return set()
    out = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            val = node.value.strip()
            if len(val) >= _LIT_MIN and "\n" not in val:
                out.add(val)
    return out


def grade(transcript, producer, before, after, text):
    """The WHOLE decision for one pair, given nothing but four strings.

    IT TAKES ITS INPUTS RATHER THAN FETCHING THEM, and that is not tidiness:
    every control in selftest_20ee.py fires THIS function on a planted pair, so
    what the suite exercises is the rule the page publishes and not a
    re-statement of it (P34's discipline, three instruments along).

    Returns None when the producer did not move -- which includes the
    changed-and-changed-back case, where the transcript is NOT stale and saying
    so would be a false accusation.
    """
    if before is None or after is None or before == after:
        return None
    sig_before, sep_before = code_signature(before, producer)
    sig_after, sep_after = code_signature(after, producer)
    new = sorted(v for v in literals(after) - literals(before)
                 if v not in text) if producer.endswith(".py") else []
    return {"transcript": transcript, "producer": producer, "wide": False,
            "grade": "CODE" if sig_before != sig_after else "PROSE-ONLY",
            "separated": sep_before and sep_after,
            "archival": is_archival(transcript),
            "witness": new}


def scan(rev=AS_OF):
    """Every figure this file publishes, from one commit and nothing else."""
    tracked = set(git("ls-tree", "-r", "--name-only", rev).splitlines())
    strict, missed = pathlist.pairs_at(rev, tracked)
    wide_all = widen(missed, tracked)
    wide = [(t, p) for t, p in wide_all if WIDENED_VERDICT.get(t)]
    order = last_touch(rev)
    rows, unresolved = [], []
    for transcript, producer in sorted(strict) + sorted(wide):
        if transcript not in order or producer not in order:
            unresolved.append(transcript)
            continue
        if order[producer] >= order[transcript]:
            continue                      # the producer has not moved since
        at_transcript = git("log", "--format=%H", "-1", rev, "--",
                            transcript).strip()
        row = grade(transcript, producer, blob(at_transcript, producer),
                    blob(rev, producer), blob(rev, transcript) or "")
        if row is None:
            continue                      # changed and changed back, or absent
        row["wide"] = (transcript, producer) in wide
        rows.append(row)
    return {"rev": rev, "tracked": len(tracked), "strict": strict,
            "missed": missed, "wide_all": wide_all, "wide": wide,
            "rows": rows, "unresolved": unresolved}


