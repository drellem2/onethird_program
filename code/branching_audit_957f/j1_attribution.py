def score(where, claim, verdict, why):
    """One attribution, scored.  UNVERIFIABLE is its own answer and is never
    silently folded into AGREES -- an attribution this script could not read is
    a fact about this script and appears as its own row."""
    {"AGREES": AGREE, "WRONG COMMIT": WRONG,
     "UNVERIFIABLE": UNVERIF}[verdict].append((where, claim))
    print("     %-46s %-14s %s" % (claim[:46], verdict, why[:60]))
    if verdict == "WRONG COMMIT":
        R.finding("%s attributes %s -- %s" % (where, claim, why))
    if verdict == "UNVERIFIABLE":
        R.selferr("%s: this script could not extract %r to score it (%s)"
                  % (where, claim, why))


