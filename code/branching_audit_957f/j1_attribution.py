def ground_truth(repo=L.REPO, head=None):
    """(member -> [commits], commit -> [members]).  Route one, cross-checked
    against route two.  Returns (per_member, per_commit, disagreements)."""
    hd = head or L.head_rev(repo=repo)
    rng = "%s..%s" % (L.REV_A218, hd)
    per_member = {}
    for f in L.FIVE:
        per_member[f] = L.log_paths(rng, L.A218_DIR + "/" + f, repo=repo)
    # route two: every commit in the range that touched the directory, asked
    # what IT touched
    dir_commits = L.log_paths(rng, L.A218_DIR, repo=repo)
    per_commit = {}
    for h in dir_commits:
        hit = [f for f in L.FIVE
               if (L.A218_DIR + "/" + f) in L.show_names(h, repo=repo)]
        if hit:
            per_commit[h] = sorted(hit)
    # the two must agree
    bad = []
    for f in L.FIVE:
        one = sorted(per_member[f])
        two = sorted(h for h, fs in per_commit.items() if f in fs)
        if one != two:
            bad.append((f, [x[:8] for x in one], [x[:8] for x in two]))
    return per_member, per_commit, bad


