def short(hs):
    return sorted(h[:8] for h in hs)


# --- the extractor.  Every claim of the form "X was touched by Y" ------------
def g4_member_rows(out):
    """member -> the commit prefixes its own sha row names."""
    rows = {}
    for line in out.splitlines():
        tok = line.split()
        if len(tok) >= 2 and tok[0] in L.FIVE:
            if tok[1] == "CHANGED" and line.count("(") >= 1:
                inner = line.split("(", 1)[1].split(")", 1)[0]
                rows[tok[0]] = sorted(x.strip() for x in inner.split(",")
                                      if x.strip())
            elif tok[1] == "same":
                rows[tok[0]] = []
    return rows


def g4_commit_rows(out):
    """commit prefix -> (ticket, [members]) from the ATTRIBUTION block."""
    rows, cur = {}, None
    inblock = False
    for line in out.splitlines():
        if "ATTRIBUTION, INVERTED FROM THE SAME git log CALLS" in line:
            inblock = True
            continue
        if inblock and line.startswith("---"):
            break
        if not inblock:
            continue
        s = line.strip()
        if s.startswith("touches:") and cur is not None:
            body = s.split("touches:", 1)[1].strip()
            rows[cur] = (rows[cur][0],
                         [] if body == "none"
                         else sorted(x.strip() for x in body.split(",")))
            cur = None
            continue
        tok = s.split()
        if len(tok) >= 2 and (len(tok[0]) == 8 or tok[0] == "(none)"):
            cur = tok[0]
            rows[cur] = (tok[1], None)
    return rows


def g4_summary(out):
    """the three 'of the five, touched by …' lines -> (label, n, [members])."""
    got = []
    for line in out.splitlines():
        if "of the five, touched by" not in line:
            continue
        label, tail = line.split("touched by", 1)[1].split(":", 1)
        n = int(tail.strip().split("--")[0].strip())
        body = tail.split("--", 1)[1].strip()
        got.append((label.strip(), n,
                    [] if body == "none"
                    else sorted(x.strip() for x in body.split(","))))
    return got


def g1_touch_rows(out):
    """file -> [commit prefixes] from g1 (ii)'s 'commits touching each part'."""
    rows = {}
    for line in out.splitlines():
        s = line.strip()
        if not s.startswith(("c1_branching.py", "kern_a218.py",
                             "out_t1_tl.txt")):
            continue
        if "(" not in s or ")" not in s:
            continue
        name = s.split()[0]
        tail = s.split(")", 1)[1].strip()
        rows[name] = [] if tail == "NONE" else sorted(x.strip()
                                                      for x in tail.split(","))
    return rows


def g1_sha_rows(out):
    """file -> 'SAME' | 'CHANGED' from g1 (ii)'s REPORTED sha table."""
    rows = {}
    for line in out.splitlines():
        tok = line.split()
        if len(tok) == 5 and tok[0] in ("c1_branching.py", "kern_a218.py") \
                and tok[4] in ("SAME", "CHANGED") and tok[2] == "...":
            rows[tok[0]] = tok[4]
    return rows


