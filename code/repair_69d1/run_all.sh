#!/bin/sh
# The instrument for mg-69d1 -- the two sites left open by two audits, both in
# this ticket, neither deferred:
#
#   OPEN 1  THE STATED BOUND IS WIDER THAN THE SWEEP (mg-eaef, E5 and E4).
#           `DELETION ESTABLISHES COVERAGE DOWN TO EXPLICIT BOOLEAN OPERANDS
#           AND NO FURTHER` is read as a guarantee about every explicit boolean
#           operand, and 4 of face_complex.py's 15 are in NEITHER census
#           column, with posets.py's 2 in a file the sweep never visits.  The
#           sentence is narrowed to the sweep and all 17 are put in exactly one
#           NAMED column, `not determined` among them.                    (p1)
#
#   OPEN 2  THE ROW IS RIGHT AND ITS REASON IS INVERTED (mg-e34a, E-1).  The
#           reason mg-76cc gave for the `both together` row names a CANCELLING
#           pair, which is the one input that row does not catch.  The reason
#           is repaired; the row is not.                                  (p3)
#
# and two things that are neither:
#
#   p2  THE SUBJECTS AND THE AUDITOR, RE-RUN UNMODIFIED -- d2_deletion.py,
#       g1_provenance.py, and mg-e34a's own k4_cancel.py against the repaired
#       tree.  Nothing is edited to stay green.
#   p4  THIS DELIVERABLE, CHECKED FOR THE DEFECTS IT REMEDIES, and the KINDS of
#       artifact this repair emits enumerated with a disposition each.
#
# Pure Python 3, no dependencies, NO NETWORK.
#
# EXIT-CODE CONVENTION.  Every p*.py exits 0 iff SELF-ERRORS == 0 AND
# FINDINGS == 0.  A non-zero exit means "this script has something to report",
# never "this script is broken"; both numbers are printed separately and every
# count names its population.  PREDICTIONS.md holds the exit code predicted for
# each script BEFORE it was run, with the misses kept as written.
#
# NO PIPE ANYWHERE (mg-c2b3, mg-f922): each script's stdout is REDIRECTED, its
# exit code read from $? on the next line, and the worst propagated.  A
# pipeline's status in POSIX sh is the LAST command's, so `| tee` would let a
# red verifier hide under a green runner.
#
# NOTHING HERE WRITES INTO code/face_geometry/, code/face_geometry_instr_5f9a/,
# code/branching_audit_58da/, code/branching_audit_a218/,
# code/branching_audit_e34a/ OR code/branching_repair_76cc/.  p2 RUNS three of
# those scripts and captures their stdout; their committed transcripts are
# regenerated by their own runners and never by this one.
#
# p2 IS PREDICTED TO REPORT d2_deletion.py EXITING 1, and it does.  That is
# mg-eaef's E8 -- the claim AND THE PIN IS WHAT IT SAYS IT IS, broken because
# bfd7948 is itself a commit with a two-clause `shape` guard and is newer than
# the pin.  mg-69d1 does NOT close it.  p2 requires it to be the ONLY broken
# claim in that run, so a second break is a finding here rather than noise.
#
# Measured runtime 2026-07-31 on a 2024 laptop: 78 s total -- selftest under a
# second, p1 6 s (four control batteries plus the baseline), p2 68 s (it runs
# d2_deletion.py, which is twenty-nine batteries, plus g1 and k4), p3 3 s
# (eight c1 runs), p4 under a second.
# 40 self-test assertions; p1 4 findings-population sections, p2 3, p3 3, p4 3.
set -u
cd "$(dirname "$0")"
WORST=0

run() {
    printf '%s\n' "----- $1 -----"
    python3 -u "$1" > "out_${1%.*}.txt" 2>&1
    RC=$?
    tail -1 "out_${1%.*}.txt"
    if [ "$RC" -gt "$WORST" ]; then WORST=$RC; fi
    printf 'exit %s\n\n' "$RC"
}

run selftest_69d1.py
run p1_bound.py
run p2_rerun.py
run p3_reason.py
run p4_kinds.py

printf 'WORST EXIT: %s\n' "$WORST"
exit "$WORST"
