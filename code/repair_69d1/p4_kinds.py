"""p4_kinds.py -- WHAT KINDS OF ARTIFACT DOES A REPAIR PRODUCE, AND WAS EACH ONE
CHECKED?

THE MECHANISM BOTH OPEN SITES SHARE, stated plainly by mg-e34a's auditor:

    the repair added a ROW and a REASON, and only the row was checked.

A repair's output is more than one artifact.  Verification that covers the
primary one and not its accompanying explanation leaves the explanation
UNAUDITED BY CONSTRUCTION -- not by oversight, not by haste, but because the
verification was aimed at a different artifact.  mg-f7e1 shipped a sweep and a
sentence about the sweep, and the sentence was never measured against the sweep.
mg-76cc shipped a row and a reason for it, and the reason named an input nobody
built.  Two tickets, two kinds of second artifact, one shape.

SO THIS SCRIPT ENUMERATES THE KINDS.  Not the same-kind defects -- the KINDS.
For each kind it asks whether this repair emits one, and if it does, what
checked it.  A kind that this repair genuinely cannot emit is named with the
reason, because "not applicable" is an answer and an empty cell is not, which is
the same rule OPEN 1 is about.

AND THE DELIVERABLE IS OF THE SAME KIND AS THE DEFECT IT REPAIRS.  This repair
states bounds and gives reasons.  So the last section turns the two checks on
this instrument's own output: are ITS bounds narrower than ITS evidence, and are
ITS reasons claims that were run rather than written?

Exit 0 iff SELF-ERRORS == 0 and FINDINGS == 0.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import lib69d1 as L                                              # noqa: E402

R = L.Report(
    selfpop="every git read and worktree read this script performs, and the "
            "requirement that every path it names be readable",
    findpop="the 9 KINDS of artifact enumerated below, each against the "
            "repair's own output; every copy of the two repaired sentences "
            "found by `git grep` over the working tree; and this "
            "instrument's own bounds and reasons")

# ---------------------------------------------------------------------------
# THE ENUMERATION.  (kind, does this repair emit one, what checked it)
#
# `check` is None when the kind is NOT EMITTED; then `why` must say so with a
# reason.  A kind with neither a check nor a reason is a finding.
KINDS = [
    ("code / rows",
     True,
     "kern5f9a.boolean_operands, operand_columns and drop_boolean_operand, "
     "and g1's HALVES row, whose (script, kernel) pair is UNCHANGED",
     "p1 (ii)(iii)(iv), p3 (iii), and d2's own two new claims in p2 (i)"),

    ("reasons / rationales",
     True,
     "the corrected `both together` reason in g1 and the narrowed bound "
     "sentence in d2, face_complex.py, run_all.sh and the landing document",
     "p3 (iii) builds BOTH inputs the corrected reason names; p1 (i)(iii) "
     "scores the narrowed bound against the sweep's own rows"),

    ("labels",
     True,
     "the row label `cancellation` -> `conspiracy`.  A label is a one-word "
     "reason and it named the case the row does NOT catch",
     "p2 (ii) reads the label out of g1's own stdout; p3 (iii) measures the "
     "case it now names"),

    ("docstrings",
     True,
     "g1_provenance.py's module docstring, d2_deletion.py's module docstring, "
     "face_complex.absorb_trace's docstring, kern5f9a.condition_census's",
     "p1 (i) and p3 (i) grep the WORKING TREE for both sentences and classify "
     "every copy; a docstring is not exempt from the grep"),

    ("comments",
     True,
     "the SWEEP_FILES comment in d2_deletion.py and the HALVES comment in "
     "g1_provenance.py",
     "read by the same grep; and SWEEP_FILES is not a comment but a CONSTANT "
     "both the sweep and the table read, which is the point -- a comment "
     "saying two numbers agree is what let them disagree"),

    ("source anchors in OTHER files",
     True,
     "lib76cc.HALF_BOTH_ROW, an exact source span in a file this repair was "
     "not about, which carried the label being renamed",
     "p2 (i)-style rerun is not enough: r1_kernel.py's drop_both_half would "
     "raise `expected exactly 1 occurrence`.  Found by THIS enumeration and "
     "fixed; the run_all.sh of mg-76cc is the check"),

    ("committed transcripts",
     True,
     "out_d2_deletion.txt and mg-58da's FIVE, of which g1's is the one this "
     "repair changes; out_r1_kernel.txt and mg-76cc's four",
     "regenerated by each instrument's OWN run_all.sh, not one file at a "
     "time -- mg-76cc's r2 measures a property ACROSS mg-58da's five (they "
     "must all name one HEAD revision), and regenerating g1's alone put r2 "
     "at 3 findings.  p2 runs each subject and scores its stdout"),

    ("landing / repair documents",
     True,
     "docs/landing-mg-0b07-implicit-disjunction.md and "
     "docs/repair-mg-76cc-kernel-half-and-five-outputs.md",
     "p1 (i) and p3 (i) grep them like any other file; both carry the "
     "correction beside the sentence corrected, rather than in place of it"),

    ("commit text",
     False,
     "the commit messages of bfd7948 and 4755d02 carry the wide bound and the "
     "inverted reason",
     None),
]

L.banner("P4", "THE KINDS OF ARTIFACT A REPAIR PRODUCES, EACH CHECKED")
print("""
mg-e34a's auditor named the mechanism: the repair added a ROW and a REASON, and
only the row was checked.  The enumeration requirement applies to the KINDS of
output, not only to the same-kind defects.
""")

# ---------------------------------------------------------------------------
L.rule("(i) THE ENUMERATION")
print("   %-32s %-8s %s" % ("kind", "emitted", "what checked it"))
for kind, emitted, what, check in KINDS:
    print("   %-32s %-8s %s"
          % (kind, "yes" if emitted else "NO",
             (check or "-- NOT EMITTED --")))
    print("     %s" % what)
print()
missing = [k for k, e, _w, c in KINDS if e and not c]
R.gate(not missing,
       "%d kind(s) of artifact this repair emits have no check named: %s"
       % (len(missing), ", ".join(missing)))
unexplained = [k for k, e, w, _c in KINDS if not e and not w]
R.gate(not unexplained,
       "%d kind(s) are marked NOT EMITTED with no reason given; an empty cell "
       "is the absence of an answer" % len(unexplained))
print()

# ---------------------------------------------------------------------------
L.rule("(ii) COMMIT TEXT -- THE ONE KIND THAT CANNOT BE REPAIRED")
print("""   A commit message is immutable without rewriting history, so its
   disposition is a POINTER and not a fix.  Both wrong sentences are in
   commit text, and both are named in this repair's own text so a reader
   who arrives from `git log` can find the correction.

   THIS IS THE BRANCH THAT HONESTLY CANNOT EXHIBIT THE FIX, and the
   reason is stated rather than left as a gap.""")
print()
for rev, needle, what in (
        ("bfd7948", "EXPLICIT BOOLEAN OPERANDS AND NO FURTHER",
         "the wide bound"),
        ("4755d02", "cancel", "the inverted reason")):
    try:
        msg = L.commit_message(rev)
    except RuntimeError as e:                               # pragma: no cover
        R.selferr("cannot read the commit message of %s (%s); its row is "
                  "DROPPED" % (rev, e))
        continue
    carries = needle in msg
    pointed = L.grep(rev)
    print("   %-9s carries %-18s : %-4s   named in the repaired tree at %d "
          "site(s)" % (rev, what, "yes" if carries else "no", len(pointed)))
    R.gate((not carries) or pointed,
           "the commit message of %s carries %s and no file in the repaired "
           "tree names that commit, so a reader arriving from `git log` has "
           "no way to reach the correction" % (rev, what))
print()

# ---------------------------------------------------------------------------
L.rule("(iii) THIS DELIVERABLE, CHECKED FOR THE DEFECTS IT REMEDIES")
print("""   This repair states bounds and gives reasons.  The two defects it
   repairs are a bound stated wider than its evidence and a reason that
   was written rather than run.  So:

     A.  every BOUND this instrument states -- is it narrower than the
         evidence behind it, and does it name the population?
     B.  every REASON this instrument gives for a row -- was the input
         it names BUILT?""")
print()
print("   A. THE BOUNDS THIS INSTRUMENT STATES")
BOUNDS = [
    ("p1 (i): the quotation discriminator is a PROXIMITY test, not a path "
     "list, and it cannot tell a quotation from an assertion that cites the "
     "ticket nearby",
     "stated at the site, with the window printed beside the result; and "
     "shown non-vacuous by running unchanged against HEAD in p3 (i-b)"),
    ("p1 (ii): `not determined` reads 0 on this tree, so the column is "
     "PRINTED and not EXERCISED",
     "said in the transcript rather than left to be inferred from a table "
     "with no such row; p1 (v) exercises the partition instead, by deleting a "
     "column and requiring the totality claim to go red"),
    ("p1 (iv): the 4 nested operands are measured against the CONTROL "
     "BATTERY's artifact, which is what `CHANGES` means here -- not against "
     "the mathematics",
     "the same grain d2's own sweep uses, named so the two numbers are "
     "comparable"),
    ("p2: d2_deletion.py EXITS 1 AT HEAD for mg-eaef's E8, which this repair "
     "does NOT close",
     "named by claim text, required to be the ONLY broken claim, so a second "
     "break is a finding rather than noise"),
    ("p3 (iii): the conspiring pair is ONE constructed input, not a class",
     "it is a demonstration that the row catches something no half catches; "
     "it is not a proof that it catches every conspiracy, and this line is "
     "the difference"),
]
for i, (bound, how) in enumerate(BOUNDS, 1):
    print("     %d. %s" % (i, bound))
    print("        checked by: %s" % how)
print()
R.gate(all(how for _b, how in BOUNDS),
       "a bound this instrument states carries no account of how it is kept "
       "narrow")

print("   B. THE REASONS THIS INSTRUMENT GIVES, AND THE INPUTS THEY NAME")
REASONS = [
    ("the `both together` row catches a CONSPIRING pair and no half does",
     "BUILT in p3 (ii) and measured in p3 (iii): both halves IDENTICAL, "
     "`both together` MOVED"),
    ("the two HALF rows catch a CANCELLING pair and `both together` does not",
     "BUILT in p3 (ii) and measured in p3 (iii): both halves MOVED, `both "
     "together` IDENTICAL"),
    ("the 4 nested operands are not idle, so leaving them implicitly covered "
     "was a real over-claim",
     "BUILT in p1 (iv): each deleted alone, 4 of 4 CHANGE the artifact"),
    ("the `not swept: nested` column is what makes the partition total",
     "BUILT in p1 (v): the column deleted, the totality claim required to go "
     "red"),
    ("the pre-repair census really did leave operands in neither column",
     "BUILT in p1 (v): the two old columns recomputed on bfd7948's sources"),
]
for i, (reason, built) in enumerate(REASONS, 1):
    print("     %d. %s" % (i, reason))
    print("        %s" % built)
print()
R.gate(all("BUILT" in b for _r, b in REASONS),
       "a reason this instrument gives names an input that was not built; "
       "that is the defect this ticket is about, committed by the repair for "
       "it")
print()
print("""   AND WHAT THIS SECTION CANNOT DO.  A. and B. are lists written by
   the author of the thing they are about.  They are checkable -- every
   entry names a section that runs -- and they are not independent.  The
   independent check is an audit, and this repair does not pretend to be
   one.""")
print()

L.finish(R)
