def _owner_map(tree):
    """{node: enclosing function name} for every node under a function def."""
    cls = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef):
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    cls[sub] = node.name
    where = {}
    for fn in ast.walk(tree):
        if not isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        name = ("%s.%s" % (cls[fn], fn.name)) if fn in cls else fn.name
        for node in ast.walk(fn):
            where.setdefault(node, name)
    return where


def span(node):
    """The source span of an operand -- the only key that cannot collide.

    Not the text: `a == b` occurs more than once in face_complex.py and a text
    key merges two operands into one.  Not (function, kind, text) either --
    that triple is undefined for an operand outside every deciding condition,
    which is precisely the population A-2 is about.
    """
    return (node.lineno, node.col_offset, node.end_lineno, node.end_col_offset)


def all_boolean_operands(src, fname):
    """EVERY operand of EVERY `and`/`or` ANYWHERE IN THE MODULE.

    No filter of any kind: not by statement form, not by whether the condition
    decides a return, not by nesting.  This is what the phrase denotes when it
    is written without the deciding-condition qualifier, and it is walked here
    so the phrase can be scored rather than granted.
    """
    tree = ast.parse(src)
    where = _owner_map(tree)
    out = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.BoolOp):
            continue
        for value in node.values:
            out.append({"file": fname, "func": where.get(node, "<module>"),
                        "op": "or" if isinstance(node.op, ast.Or) else "and",
                        "text": ast.get_source_segment(src, value),
                        "line": value.lineno, "span": span(value)})
    return out


def deciding_conditions_mine(src):
    """[(function, kind, condition node)] -- MY reading of kern5f9a's rule.

    The rule as kern5f9a states it: `decides a return` is either the test of
    an `if` whose body returns, or the value of a `return` itself.  Written
    from that sentence, and checked against the shipped walker span for span
    in the selftest before any subtraction rests on it.
    """
    tree = ast.parse(src)
    cls = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef):
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    cls[sub] = node.name
    out = []
    for fn in ast.walk(tree):
        if not isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        name = ("%s.%s" % (cls[fn], fn.name)) if fn in cls else fn.name
        for node in ast.walk(fn):
            if isinstance(node, ast.If):
                if any(isinstance(s, ast.Return) for s in ast.walk(node)):
                    out.append((name, "guard", node.test))
            elif isinstance(node, ast.Return) and node.value is not None:
                out.append((name, "value", node.value))
    return out


def deciding_boolean_operands(src, fname):
    """The same walk, restricted to what lies inside a deciding condition.

    This is the population `kern5f9a.boolean_operands` computes and the one
    mg-69d1's four columns classify.  Recomputed here so the difference
    between the two populations is a subtraction this instrument performed.
    """
    out = []
    for func, kind, cond in deciding_conditions_mine(src):
        for node in ast.walk(cond):
            if not isinstance(node, ast.BoolOp):
                continue
            for value in node.values:
                out.append({"file": fname, "func": func, "kind": kind,
                            "top": node is cond,
                            "op": "or" if isinstance(node.op, ast.Or)
                                  else "and",
                            "text": ast.get_source_segment(src, value),
                            "line": value.lineno, "span": span(value)})
    return out


