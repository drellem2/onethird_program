def grep_sites(needle, rev=None, repo=REPO):
    """[(path, line)] for every line containing `needle`.

    Over the WORKING TREE with untracked files included when `rev` is None --
    a site this repair has written and not yet committed is still a site --
    and over a revision otherwise, which is how the control at Q3_REV_PIN is
    taken.
    """
    args = ["grep", "-n", "-F"]
    args += [needle, rev] if rev else ["--untracked", needle]
    out = git_quiet(*args, repo=repo)
    got = []
    for line in out.splitlines():
        if not line.strip():
            continue
        rest = line.split(":", 1)[1] if rev else line
        path, _, tail = rest.partition(":")
        got.append((path, tail.split(":", 1)[0]))
    return got


def _lines(path, rev=None, repo=REPO, _cache={}):
    key = (repo, rev, path)
    if key not in _cache:
        if rev:
            _cache[key] = git_show(rev, path, repo=repo).splitlines()
        else:
            try:
                _cache[key] = read_worktree(path, repo=repo).splitlines()
            except (IOError, OSError):
                _cache[key] = []
    return _cache[key]


def window(path, lineno, rev=None, span_=3, repo=REPO):
    lines = _lines(path, rev=rev, repo=repo)
    i = int(lineno) - 1
    return "\n".join(lines[max(0, i - span_):i + span_ + 1])


def disposition(path, lineno, rev=None, repo=REPO):
    """mg-2c77's three labels, from mg-2c77's rule.

    QUALIFIED if the words `deciding condition` stand within 3 lines of the
    site in the same file.  A QUOTATION if `NO FURTHER` or `is read as` stands
    in the same window -- the two markers of the wide BOUND being quoted in
    order to correct it, which is a different sentence about a different
    thing.  Otherwise the site asserts the census unqualified.
    """
    w = window(path, lineno, rev=rev, repo=repo)
    if any(m in w for m in QUOTE_MARKERS):
        return "quotes the wide BOUND, not the census"
    if QUALIFIER in w:
        return "census, QUALIFIED"
    return "*** census, UNQUALIFIED"


def is_mine(path):
    """Is `path` an artifact of THIS repair?

    The instrument directory AND this repair's own document, because a
    document is as much a live claim as a docstring is and excluding it by
    living in `docs/` would be a population drawn to be easy to pass.
    """
    return path.startswith(MINE_DIR + "/") or "mg-8d5e" in path


def score_all(rev=None, repo=REPO):
    """[(path, line, disposition)] over every site stating the term."""
    return [(p, n, disposition(p, n, rev=rev, repo=repo))
            for p, n in grep_sites(TERM, rev=rev, repo=repo)]


