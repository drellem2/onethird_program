def files_of(rev, repo=REPO):
    return set(git("show", "--name-only", "--format=", rev, repo=repo).split())


def read_worktree(rel, repo=REPO):
    with open(os.path.join(repo, rel)) as fh:
        return fh.read()


def dirty_paths(repo=REPO):
    out = git("status", "--porcelain", "-z", "--untracked-files=all",
              repo=repo)
    return [e[3:] for e in out.split("\0") if len(e) > 3]


def clone(mutate=None, message="mg-8d5e scratch commit"):
    """A clone of this worktree with the working tree carried and COMMITTED.

    Committed, because everything r1 measures is derived from `git log` and
    an edit left in the working tree is invisible to every one of those
    derivations.  A probe that comes back unchanged because it never existed
    looks exactly like a probe that came back unchanged because the anchor
    held.
    """
    tmp = tempfile.mkdtemp(prefix="mg8d5e-")
    tree = os.path.join(tmp, "repo")
    subprocess.run(["git", "clone", "-q", "--no-hardlinks", REPO, tree],
                   check=True, capture_output=True, text=True)
    for rel in dirty_paths():
        src, dst = os.path.join(REPO, rel), os.path.join(tree, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if os.path.isfile(src):
            shutil.copy(src, dst)
        elif os.path.isfile(dst):
            os.remove(dst)
    if mutate:
        mutate(tree)
    subprocess.run(["git", "-C", tree, "add", "-A"], check=True,
                   capture_output=True, text=True)
    subprocess.run(["git", "-C", tree, "-c", "user.name=mg-8d5e",
                    "-c", "user.email=mg-8d5e@local", "commit", "-q",
                    "--allow-empty", "-m", message],
                   check=True, capture_output=True, text=True)
    return tmp, tree


def clone_at(rev):
    """A clone checked out at `rev`, with NOTHING of this worktree carried.

    Used for a before/after control: a clone that carried the working tree
    would answer about this repair whatever revision it was asked about.
    """
    tmp = tempfile.mkdtemp(prefix="mg8d5e-at-")
    tree = os.path.join(tmp, "repo")
    subprocess.run(["git", "clone", "-q", "--no-hardlinks", REPO, tree],
                   check=True, capture_output=True, text=True)
    subprocess.run(["git", "-C", tree, "checkout", "-q", rev],
                   check=True, capture_output=True, text=True)
    return tmp, tree


