def _leading_int(s):
    out = ""
    for ch in s.strip():
        if ch.isdigit():
            out += ch
        else:
            break
    return int(out) if out else None


def findings_of(out):
    """The FINDING lines a script books AS ITS OWN -- indented by exactly
    three spaces and standing after the trailer that counts them.  Both
    discriminators, because a `FINDING:` line quoted from a nested transcript
    at six spaces is not the outer script's finding."""
    got, started = [], False
    for line in out.splitlines():
        if line.startswith("FINDINGS:"):
            started = True
            continue
        if started and line.startswith("   FINDING: ") \
                and not line.startswith("    "):
            got.append(line[len("   FINDING: "):].strip())
    return got


def trailer_counts(out):
    s = f = None
    for line in out.splitlines():
        if line.startswith("SELF-ERRORS:"):
            s = _leading_int(line.split(":", 1)[1])
        elif line.startswith("FINDINGS:"):
            f = _leading_int(line.split(":", 1)[1])
    return s, f


def normalise_revs(text):
    """Every hex token of 7+ characters replaced by <rev>.

    A revision that moved is not a finding that changed, and comparing a
    finding set across revisions without this compares the shas.
    """
    out = []
    for tok in text.replace(",", " , ").split(" "):
        bare = tok.strip(".,;:`'\"()")
        if len(bare) >= 7 and bare and all(c in "0123456789abcdef"
                                           for c in bare):
            out.append(tok.replace(bare, "<rev>"))
        else:
            out.append(tok)
    return " ".join(out)


