def git(*args, **kw):
    repo = kw.pop("repo", REPO)
    return subprocess.run(["git", "-C", repo] + list(args), check=True,
                          capture_output=True, text=True).stdout


def git_quiet(*args, **kw):
    """stdout, or "" on a non-zero exit.  For reads that may legitimately
    fail -- a path absent at a revision, a grep that matches nothing."""
    repo = kw.pop("repo", REPO)
    p = subprocess.run(["git", "-C", repo] + list(args),
                       capture_output=True, text=True)
    return p.stdout if p.returncode == 0 else ""


def git_show(rev, path, repo=REPO):
    return git_quiet("show", "%s:%s" % (rev, path), repo=repo)


def resolve(rev, repo=REPO):
    return git("rev-parse", rev, repo=repo).strip()


def head_rev(repo=REPO):
    return resolve("HEAD", repo=repo)


def subject(rev, repo=REPO):
    return git("log", "-1", "--format=%s", rev, repo=repo).strip()


def last_touching(path, rev="HEAD", repo=REPO):
    return (git("log", "-1", "--format=%H", rev, "--", path,
                repo=repo).strip() or None)


def last_lacking(path, marker, rev="HEAD", repo=REPO):
    """The newest commit at or before `rev` where `marker` is NOT in `path`.

    Used to reach `libe34a.py as it stood before this repair` without naming
    a revision.  Anchored on the property -- the absence of the function that
    IS the repair -- and so it answers correctly both before this repair is
    committed (it returns HEAD) and after (it returns the parent).  A literal
    would have been wrong on one side of that commit, and the file's history
    would re-point on the next unrelated edit, which is A-1.
    """
    for h in git("log", "--format=%H", rev, "--", path, repo=repo).split():
        if marker not in git_show(h, path, repo=repo):
            return h
    return None


def base_before_dir(dirpath, rev="HEAD", repo=REPO):
    """The newest commit at or before `rev` where `dirpath` does not exist.

    The base this repair's own diff is taken against, DERIVED from the
    property `this directory is not there yet` rather than named.  A literal
    base revision would be one more anchor to re-point, in a script whose
    subject is anchors that re-point.
    """
    for h in git("log", "--format=%H", rev, repo=repo).split():
        if not git_quiet("ls-tree", h, "--", dirpath, repo=repo).strip():
            return h
    return None


def changed_paths(base, repo=REPO):
    """Every path this repair touches: committed since `base`, modified in
    the working tree, or untracked.  A union, because a repair half committed
    is still a repair and a list that only counts one of the three is a
    population that moves with when it is asked."""
    out = set(git("diff", "--name-only", base, repo=repo).split())
    out |= set(p for p in dirty_paths(repo=repo) if p)
    return sorted(out)


