#!/bin/sh
# The instrument for mg-8d5e -- the two sites left open by mg-2c77's audit of
# the mg-69d1 repair (d01ff32).  Neither deferred.
#
#   A-1  A DERIVED ANCHOR RE-POINTED WHEN A SENTENCE WAS EDITED.  `libe34a`
#        derived REPAIR_REV as the last commit that touched g1_provenance.py;
#        mg-69d1 touched that file to correct a SENTENCE, so the anchor
#        followed the edit and both sides of k1's pre-repair comparison became
#        mg-76cc's ALREADY-REPAIRED predicate.  The anchor is re-derived from
#        the PROPERTY, PINNED, and the two COMPARED.                (r1, r2)
#
#   A-2  A TERM IN A COUNT DENOTED MORE THAN THE COUNT COVERED.  `explicit
#        boolean operand` denotes 39 operands in the census's two files; the
#        table classifies the 17 inside a deciding condition.  The TERM is
#        repaired, not the walk -- the bound sentence already names the
#        deciding conditions and is correct.                            (r3)
#
# and one thing that is neither:
#
#   r4  THIS DELIVERABLE, CHECKED FOR THE DEFECTS IT REPAIRS -- every anchor it
#       derives, perturbed; every term it counts with, scored at every site;
#       every path it changes, in a named kind.
#
# r2 (v) RE-RUNS mg-2c77's OWN q3 AND q4 UNMODIFIED.  q3's census finding is
# gone; q4 STILL FIRES, and that is a defect in the auditor rather than in the
# repair -- its gate compares REVISION identity where the property is FILE
# identity, and its own message now says a value moved from 4755d029 to
# 4755d029.  Measured and pointed at in r2 (v); mg-2c77's record is not
# edited here.
#
# Pure Python 3, no dependencies, NO NETWORK.
#
# EXIT-CODE CONVENTION.  Every r*.py exits 0 iff SELF-ERRORS == 0 AND
# FINDINGS == 0.  A non-zero exit means "this script has something to report",
# never "this script is broken"; the two numbers are printed separately and
# every count names its population.  PREDICTIONS.md holds the exit code
# predicted for each script BEFORE any of them existed, with the misses kept
# as written.
#
# NO PIPE ANYWHERE (mg-c2b3, mg-f922): each script's stdout is REDIRECTED and
# `$?` is read on the next line.  A pipeline's status in POSIX sh is the LAST
# command's, so `| tee` would let a red verifier hide under a green runner.
#
# NOTHING HERE WRITES INTO code/branching_audit_e34a/, code/repair_69d1/,
# code/audit_2c77/, code/face_geometry_instr_5f9a/ or code/face_geometry/.
# r1 and r4 mutate clones under the system temp directory; r2 RUNS
# k1_prerepair.py, q3_operands.py and q4_prerepair.py and captures their
# stdout -- none of the three writes a file.  The transcripts of those suites
# are regenerated by THEIR OWN runners -- `code/branching_audit_e34a/
# run_all.sh` and `code/repair_69d1/run_all.sh` -- and never by this one.
#
# RUNTIME.  r2 runs k1_prerepair.py -- 21 pinned g1 runs across 7 clones --
# and then mg-2c77's own q4_prerepair.py, which runs k1 a second time: about
# ten minutes on its own.  r1 builds five clones and runs mg-e34a's selftest
# in three of them.  Roughly twelve minutes in all; everything other than r2
# is under a minute.
set -u
cd "$(dirname "$0")"
WORST=0

run() {
    printf '%s\n' "----- $1 -----"
    python3 -u "$1" > "out_${1%.*}.txt" 2>&1
    RC=$?
    tail -1 "out_${1%.*}.txt"
    if [ "$RC" -gt "$WORST" ]; then WORST=$RC; fi
    printf 'exit %s\n\n' "$RC"
}

run selftest_8d5e.py
run r1_anchor.py
run r2_kernel_half.py
run r3_term.py
run r4_self.py

printf 'WORST EXIT: %s\n' "$WORST"
exit "$WORST"
