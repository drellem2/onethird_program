def link_1skeleton(P, sigma, facets):
    """(vertices, edge-weight dict) of the weighted 1-skeleton of link(sigma),
    weights = number of facets of F(P) containing the 2-face.  Brute force from
    the facet list; the localisation theorem is not used."""
    s = set(sigma)
    cont = [set(f) - s for f in facets if s <= set(f)]
    verts = sorted(set().union(*cont)) if cont else []
    idx = {v: i for i, v in enumerate(verts)}
    ew = {}
    for f in cont:
        r = sorted(f)
        for a in range(len(r)):
            for b in range(a + 1, len(r)):
                k = (idx[r[a]], idx[r[b]])
                ew[k] = ew.get(k, 0) + 1
    return verts, ew


def lambda2_weighted(nv, ew):
    """Second largest eigenvalue of the random walk on a weighted graph, i.e.
    the largest eigenvalue of D^{-1/2} W D^{-1/2} restricted to the orthogonal
    complement of D^{1/2}1.  Symmetric dense Jacobi.  Returns None if the graph
    has no edge."""
    if nv == 0 or not ew:
        return None
    deg = [0.0] * nv
    for (i, j), w in ew.items():
        deg[i] += w
        deg[j] += w
    if any(d == 0 for d in deg):
        # isolated vertex: the walk is not irreducible; treat as lambda_2 = 1
        return 1.0
    import math
    A = [[0.0] * nv for _ in range(nv)]
    for (i, j), w in ew.items():
        v = w / math.sqrt(deg[i] * deg[j])
        A[i][j] = v
        A[j][i] = v
    # deflate the Perron vector sqrt(deg), eigenvalue 1
    tot = sum(deg)
    u = [math.sqrt(d / tot) for d in deg]
    for i in range(nv):
        for j in range(nv):
            A[i][j] -= 2.0 * u[i] * u[j]
    ev = jacobi_eigenvalues(A)
    # the deflation moved the eigenvalue 1 to -1; the rest are untouched.
    ev = sorted(ev)
    # remove one copy of the shifted Perron value (-1)
    k = min(range(len(ev)), key=lambda t: abs(ev[t] + 1.0))
    ev.pop(k)
    return max(ev) if ev else None


def jacobi_eigenvalues(Ain, tol=1e-13, sweeps=200):
    n = len(Ain)
    A = [row[:] for row in Ain]
    import math
    for _ in range(sweeps):
        off = 0.0
        for i in range(n):
            for j in range(i + 1, n):
                off += A[i][j] * A[i][j]
        if off < tol * tol:
            break
        for p in range(n):
            for q in range(p + 1, n):
                if abs(A[p][q]) < 1e-16:
                    continue
                theta = (A[q][q] - A[p][p]) / (2.0 * A[p][q])
                t = (1.0 if theta >= 0 else -1.0) / (abs(theta) + math.sqrt(theta * theta + 1.0))
                c = 1.0 / math.sqrt(t * t + 1.0)
                s = t * c
                for k in range(n):
                    akp = A[k][p]
                    akq = A[k][q]
                    A[k][p] = c * akp - s * akq
                    A[k][q] = s * akp + c * akq
                for k in range(n):
                    apk = A[p][k]
                    aqk = A[q][k]
                    A[p][k] = c * apk - s * aqk
                    A[q][k] = s * apk + c * aqk
    return [A[i][i] for i in range(n)]
