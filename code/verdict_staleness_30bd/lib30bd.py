#!/usr/bin/env python3
"""mg-30bd — THE CLASSIFIER FOR VERDICT-STALENESS, AND THE TOKEN SET IS THE INSTRUMENT.

WHY THIS EXISTS.  `code/asof_census_20ee` measures a population defined by `path:NNN`
ADDRESSES into files the instrument does not own.  mg-20ee said in as many words that "the
verdicts are not affected ... this must not be reported as a correctness defect", and that
sentence is TRUE OF THE POPULATION THAT CENSUS MEASURES AND FALSE OF THE CORPUS.  A
transcript can drift in its VERDICTS without any address moving, and such a transcript is
invisible to an address classifier BY CONSTRUCTION — it is not looking for that.

`code/species_extent_audit_6cb9` is the existence proof and it was found BY ACCIDENT, by
p6e4f, while pinning something else: its committed `out_a1_bothways.txt` says
`A1 TOTAL BAD: 1` with a `*** MISSED ***` row and two `*** EXTENT WIDER ***` rows; the same
script at HEAD today says `A1 TOTAL BAD: 0` and those rows are gone.  6cb9 is NOT among
mg-20ee's 44 candidates, so it sits outside the corrected population of 32 entirely.

A stale ADDRESS relocates a reader wrongly.  A stale VERDICT says the corpus measured
something it no longer measures — and it reads as a finding.  This module measures the
second class.  IT REPAIRS NOTHING: a verdict that has moved is a finding about the corpus and
needs an owner per instance, not a batch repair.

------------------------------------------------------------------------------------------
THE CLASSIFICATION, IN ORDER.  Each step is a REFINEMENT of the one before, and the first
two are BORROWED rather than re-spelled, because a second definition of "benign" is a second
place for the definition to drift.

  0  IDENTICAL          the committed bytes and the regenerated bytes are equal.
  1  BENIGN/f771        `lib_f771.verdict_for` says NOISE — i.e. the difference is entirely
                        inside mg-f771's declared N1 (an absolute path to a checkout of this
                        repository) and N2 (decimal seconds), under N3's prefix rule.  This
                        is the TIMING family and the CHECKOUT-PATH family, and it is the
                        gate's own definition, imported and not re-implemented.
  2  BENIGN/address     under A1 (a `file.ext:NNN` or `dir/file:NNN` line address) and A2
                        (a git sha, an ISO date, a clock time) the two texts become
                        equivalent.  This is mg-c824/mg-20ee's ADDRESS family and the
                        AS-OF-BLOCK family.
  3  VERDICT-STALE      the two texts differ in their VERDICT LINES (below).  THE HEADLINE.
  4  NON-VERDICT        they differ, but not in any verdict line.  Corpus-size counts land
                        here, and so does everything else this instrument has no name for.

WHY CORPUS-SIZE IS NOT MASKED, THOUGH THE TICKET NAMES IT A BENIGN FAMILY.  Masking it means
masking INTEGERS, and `A1 TOTAL BAD: 1 -> 0` is an integer.  A mask wide enough to eat
"530 markdown file(s) -> 531" and narrow enough to spare "TOTAL BAD: 1 -> 0" is a mask about
nouns, i.e. a list of the corpus nouns somebody has already looked at — mg-f771's own
warning about a wider normaliser being "an unfalsifiable escape hatch" applies exactly.  So
corpus-size is NOT proven benign here; it falls into bucket 4 and is COUNTED there.  Nothing
in the headline depends on that choice, because the headline is defined by MOVEMENT IN
VERDICT LINES and not by what is left over.

------------------------------------------------------------------------------------------
THE TOKEN SET.  `TOKENS` below is the instrument and it must be quotable, so it is a
hand-typed literal and not a regex over "words that look like verdicts".  A line is a
VERDICT LINE iff, after normalisation, it contains at least one token as a whole word.

Each token is ALL-CAPS.  That is a rule and not an accident: this corpus writes its graded
outcomes in capitals (`*** MISSED ***`, `VERDICT: RED`, `TOTAL BAD: 1`, `CAUGHT`, `HELD`)
and writes its prose in sentence case, so the case requirement is most of the selectivity.
The tokens were chosen by reading the ALL-CAPS frequency table over all 1051 tracked
transcripts at HEAD (the derivation is in README §2) and keeping the words that name a
GRADED OUTCOME or LABEL ONE, then dropping the ones that are only ever prose emphasis
(`THE`, `AND`, `NOT`, `THIS`, `EVERY`, ...).

WHAT THE CHOICE COSTS, STATED RATHER THAN DISCOVERED:
  * OVER-INCLUSION.  A corpus-size count that happens to sit on a line carrying a token
    ("PASS -- 530 file(s)") is graded VERDICT-STALE by this instrument.  That is why the
    verdict-stale bucket is SPLIT into TOKEN-MOVE (a token appeared, vanished or changed)
    and NUMBER-ON-A-VERDICT-LINE (the tokens are the same multiset and a number under one
    moved).  Both are reported; only the first is the strong claim.
  * UNDER-INCLUSION.  A verdict stated in a word not on the list, or in lower case, is
    invisible here.  That is a blind spot of the TOKEN SET, and it is distinct from the
    blind spot of the METHOD (README §5).
"""

