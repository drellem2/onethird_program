# THE DECLARATION — A TRANSCRIPT THAT SAYS IT CANNOT BE A FIXED POINT (mg-5491)
# ======================================================================================
#
# WHY THE CLASSIFIER NEEDED ONE.  `code/audit_c067/out_c1_rebase.txt` opens
#
#     A TRUE RECORD WHOSE OWN PRODUCER CAN NO LONGER SEE IT.  DO NOT RE-RUN THIS.
#
# and explains, in the file, that a re-run writes a FALSE 0 over a TRUE 5 because its
# producer pairs commits by subject inside `git log -n 40`.  mg-30bd's sweep re-ran it and
# graded the result, so the record carries the instrument's own blindness as a finding about
# the corpus.  `code/verdict_delivery_bf3f`'s four read the LIVE mg verdict and mail stream:
# no commit can make them reproduce, and re-running them measures a different afternoon.
# Those five are not findings about this repository at all, and reading them one at a time is
# how that was found.  THE GENERAL REPAIR IS NOT FIVE EXCLUSIONS, IT IS A NOTION: give the
# classifier a way for a transcript to say `I am not a fixed point, and here is why`, and the
# whole class stops being false positives instead of these five stopping.
#
# WHY IT IS NOT AN UNFALSIFIABLE ESCAPE HATCH, WHICH IS THE OBJECTION IT HAS TO SURVIVE —
# mg-f771's own warning about a wider normaliser, one instrument along.  Four things, and the
# third is the one that does the work:
#
#   1  IT IS A HAND-TYPED LITERAL, not a regex over "prose that sounds like a disclaimer".
#      `DO NOT RE-RUN THIS` in a sentence is not a declaration; this line is.
#   2  IT MUST BE IN THE FIRST `DECLARATION_WINDOW` LINES.  A declaration is made at the
#      HEAD of the file it is about.  The window is what stops a QUOTATION exempting the
#      transcript that quotes it — and this estate's instruments quote each other constantly,
#      including `report.py`, which prints this literal in its own §3b.
#   3  IT IS CHECKED IN BOTH DIRECTIONS.  A transcript declaring itself unable to reproduce,
#      WHICH THEN REPRODUCES BYTE-IDENTICALLY IN THE SWEEP, is a FALSE DECLARATION and
#      report.py §3b says so as a finding.  That is the same discipline mg-937c put on
#      `cause: RECORD-DISAGREES`: a hand field the record can contradict is a claim, and a
#      hand field it cannot is a laundry.
#   4  NOTHING IS HIDDEN.  Every declaration is COUNTED AND LISTED with the bucket it would
#      have carried, so the exemption class is exactly as visible as the stale class, and it
#      grows in public.
#
# WHAT IT STILL CANNOT CHECK, SAID HERE RATHER THAN DISCOVERED LATER: that the REASON is the
# right reason, or that no commit could have made the transcript reproduce.  A declaration is
# a judgement by the transcript's owner and this is an ADDRESS for it, not a proof of it.

DECLARATION = "NOT-A-FIXED-POINT:"

# 20 lines.  Long enough for a `#`-commented note header to carry the marker after a rule and
# a title, short enough that no listing, table or quotation in the body of a transcript can
# reach it.  Measured against the corpus rather than guessed: the five transcripts this
# repair covers carry theirs at lines 2-6.
DECLARATION_WINDOW = 20


def declaration(text):
    """The transcript's own declaration that it is not a fixed point, or None.

    Returns the REASON — whatever follows the marker on its line.  An empty reason comes
    back as `""` and is NOT honoured: report.py counts it MALFORMED and grades the
    transcript exactly as if the line were not there, because a marker with nothing after it
    is an exemption nobody signed.  The two are different answers and `None` is neither.
    """
    for line in text.split("\n")[:DECLARATION_WINDOW]:
        s = line.strip().lstrip("#").strip()
        if s.startswith(DECLARATION):
            return s[len(DECLARATION):].strip()
    return None


# ======================================================================================
# THE HISTORY-WALK LINE — A DETECTOR THAT WAS NARROWER THAN THE FAMILY IT NAMED (mg-aff1)
# ======================================================================================
#
# WHAT IT IS FOR.  `report.py` puts a NOTE on a verdict-stale entry whose moved lines are a
# `git log` walk, because that entry's cause is legible from the lines themselves and a
# reader should not have to re-derive it.  It annotates; it grades nothing, moves no bucket
# and changes no count.  That is why widening it is cheap and why getting it wrong is not:
# a NOTE is an assertion about somebody else's transcript, printed in this corpus's record.
#
# THE DEFECT.  It lived in `report.py` as `^\s*(?:HEAD:\s*)?<sha>\s+\S` — a masked sha at
# the START of the line.  mg-937c's own arm measured what that missed and said so: 5 of the
# 9 rows the baseline calls HISTORY-WALK carried no NOTE, found by READING them rather than
# by the detector, and named three times as owed and as wanting its own commit.  The newest
# of the nine arrived in mg-5491's first caught growth event and was one of the five, so the
# under-detection was getting worse in the rows that were arriving.
#
# THE TWO SHAPES IT MISSED, AND THE ONE IT STILL DOES:
#
#   1  A LABELLED SHA.  `by <sha>  repair: ...`, `at <sha>: ## ...`,
#      `the tip      <sha> <date>  docs: ...` — a walk whose format string puts a word in
#      front of the sha, or a colon behind it.  Repaired here.
#   2  `HEAD's subject : <subject>` — named in mg-937c's own §6.4 as the shape it misses.
#      A hand-typed literal, exactly like DECLARATION and for the same reason.  Repaired.
#   3  A BARE COMMIT SUBJECT with no sha and no label at all.  NOT repaired, and §6.4 of
#      out_owners_937c.txt now measures why rather than asserting it: see `walk_bare_subject`.
#
# WHY THE WINDOW, WHICH IS THE HALF THAT DOES THE WORK.  `a <sha> anywhere in the line` is
# the obvious widening and it is REFUTED ON THE RECORD, not argued against: it fires on
# every FINDING sentence that happens to quote a sha, and out_owners_937c.txt §6.4 prints
# the count.  A walk line puts its sha in a COLUMN, so the sha sits at the head of the line
# behind at most a short word label — letters and spaces only, no punctuation, because
# `FINDING: ... deleted by <sha> ...` and `N20 H8: the <sha> table's` are prose and their
# prefixes say so.  The window is measured, not chosen: the widest true label on the record
# is `the tip      ` at 13 characters, and the hit set is IDENTICAL at every window from 13
# to 24, so 16 is inside a plateau rather than tuned to a corpus.
#
# WHAT NO WINDOW CAN DO, AND WHY THE THIRD SHAPE STAYS OPEN.  A bare commit subject is
# prose, and the only non-fuzzy way to know one is to compare it against the history it came
# from.  THAT IS REFUSED ON THIS DIRECTORY'S OWN GROUNDS: a detector that reads `git log`
# answers differently on different days, so the transcript carrying its answer stops being a
# function of repo state — which is mg-e720's family, the very class this NOTE names.  A
# history-walk detector that walked history would be a member of the population it counts.

WALK_LABEL_WINDOW = 16

# The `HEAD's subject` label, hand-typed for DECLARATION's reason 1: a literal, not a regex
# over "prose that sounds like a commit subject".
HEAD_SUBJECT = re.compile(r"^\s*HEAD's subject\s*:\s*\S")

WALK_SHA = re.compile(r"^(?:HEAD:\s*)?[A-Za-z ]{0,%d}<sha>[:,]?\s+\S" % WALK_LABEL_WINDOW)


def is_walk_line(line):
    """Is this masked line one row of a `git log` walk?  Pure string -> bool."""
    return bool(WALK_SHA.match(line) or HEAD_SUBJECT.match(line))


# THE THREE THAT FAILED, KEPT RATHER THAN DELETED — `naive_mask`'s arrangement one detector
# along.  `selftest_30bd.py` runs them on planted strings and `owners_937c.py` runs them over
# the whole record on every suite run, so the refutations are measurements and not sentences.
# The first is THE RULE THIS ONE REPLACES: a repair whose BEFORE is not printed beside its
# AFTER is an assertion, so the narrow rule ships and §6.4 reports both counts.

WALK_LINE_START = re.compile(r"^\s*(?:HEAD:\s*)?<sha>\s+\S")

WALK_ANYWHERE = re.compile(r"(?:^|\s)<sha>[:,]?\s+\S")

# A conventional-commit prefix: `instrument: `, `census+repair: `.  Reads as decisive until
# it is run — `unmutated: 0   mutated: 20`, `verdicts: wall=CONCURRENT` and
# `species_repair_a4ef: \`set -e\` appears once` have the same shape and are not subjects.
# A closed vocabulary of commit types would separate them today and rot silently tomorrow,
# which is this detector's own defect one level in: this estate's log carries `refresh`,
# `measure`, `declare`, `amend`, `land`, `discharge`, `owners`, `scope` and `census+repair`,
# and the set is open by construction.
WALK_BARE_SUBJECT = re.compile(r"^\s*[a-z][a-z0-9_]*(?:[+/][a-z0-9_]+)*:\s+\S")


def walk_line_start(line):
    """THE RULE mg-aff1 REPLACED — a masked sha at line start.  For the controls only."""
    return bool(WALK_LINE_START.match(line))


def walk_anywhere(line):
    """THE OBVIOUS WIDENING, refuted on the record.  For the controls only."""
    return bool(WALK_ANYWHERE.search(line))


def walk_bare_subject(line):
    """THE REMAINING SHAPE, undecidable from the line.  For the controls only."""
    return bool(WALK_BARE_SUBJECT.match(line))


# ======================================================================================
# THE OUT-OF-FAMILY COLUMN'S OWN POWER — A CONTROL THAT HAS NEVER FIRED IS A CLAIM (mg-cda7)
# ======================================================================================
#
# WHAT mg-aff1 SHIPPED AND WHAT IT LEFT.  The widening above went 10 hits -> 18 and reported
# two numbers, not one: ALL 8 GAINED IN-FAMILY, and THE OUT COLUMN DID NOT MOVE.  That is
# the right pair to print — 10 -> 18 alone is equally consistent with `found eight more of
# the thing` and `started matching a neighbouring thing`.  What it does not establish is
# THAT THE PAIR IS HARD TO PRODUCE.  mg-aff1's own carry-forward says so in as many words:
# is the OUT column sensitive enough to have caught a bad widening?
#
# THE COLUMN HAS POWER AND IT IS MEASURED, NOT ASSERTED.  `owners_937c.py` §6b runs the
# battery below over every quoted line in the record.  Of the candidates that gain any line
# at all, EVERY ONE moves the OUT column — the refutation of `anywhere` was not luck.
#
# AND THE COLUMN HAS A BLIND SPOT, WHICH IS STRUCTURAL AND NOT A TUNING.  The in/out split
# is a PROXY over PATHS: a line is in-family because the row it sits in was read and filed
# HISTORY-WALK, not because anybody looked at the line.  So a widening confined to lines
# INSIDE those rows moves the OUT column by exactly zero however wrong it is, and §6b prints
# how much room that leaves.  Two of the planted widenings below are in that room: `finding
# sha` and `predicted row` each gain lines, gain them ALL IN-FAMILY, and leave OUT where it
# was — mg-aff1's exact signature, on rules that are not walk detectors at all.
#
# SO `OUT UNMOVED` IS NECESSARY AND NOT SUFFICIENT, and the third column is what closes it:
# OWNERS.json's `walk_lines` carries a hand verdict for EVERY quoted line inside a
# HISTORY-WALK row, and a widening is graded on how many NOT-WALK lines it gains.  That is
# the same remedy mg-937c gave the 150 — read them one at a time and put the reading in a
# file the arm grades against the record — one level in, at the LINE instead of the ROW.
# What it does not do is decide whether a reading is RIGHT: nothing here checks that, the
# same declaration this directory already makes about `cause`, and §6b says it plainly.

import hashlib                                                     # noqa: E402


def line_key(text):
    """A stable identity for one quoted line: 12 hex of sha256 over its stripped text.

    Keyed by DIGEST rather than by text because the record's lines run to 900 characters and
    a hand file is unreadable at that width; the entry carries an excerpt beside the digest
    so a reader still sees what was read.  Keyed on the MASKED line, which is what the record
    stores, so the key is a function of the frozen sweep and not of any tree.
    """
    return hashlib.sha256(text.strip().encode("utf-8")).hexdigest()[:12]


# THE BATTERY.  Every rule is kept here rather than written inline in the arm, for the reason
# mg-aff1 moved the detector out of report.py: a rule nothing can plant a world against is a
# rule nobody can bound.  Four are the versions of the detector that have been written (the
# shipped one, the one it replaced, and the two refuted); the rest are CANDIDATES — some are
# widenings a successor might plausibly reach for, and some are bad on purpose.  They are in
# one list so that §6b grades them by the SAME two columns and nothing is graded by hand.
#
# `bad` is this file's own claim about the rule and is NOT what the arm reports on: the arm
# reports the columns and lets them disagree with it.  A field that could not disagree would
# be a label, not a measurement.
CANDIDATE_WIDENINGS = [
    ("C1", "any label character, same tail", False,
     r"^(?:HEAD:\s*)?.{0,16}<sha>[:,]?\s+\S"),
    ("C2", "drop the trailing `\\s+\\S`", False,
     r"^(?:HEAD:\s*)?[A-Za-z ]{0,16}<sha>"),
    ("C3", "let the label carry punctuation", False,
     r"^(?:HEAD:\s*)?[\w .*+()\[\]-]{0,16}<sha>[:,]?\s+\S"),
    ("C4", "window 40 — the top of the plateau", False,
     r"^(?:HEAD:\s*)?[A-Za-z ]{0,40}<sha>[:,]?\s+\S"),
    ("C5", "any `... subject :` label", False,
     r"^\s*\S.{0,20}subject\s*:\s*\S"),
    ("C6", "two shas on the line", False,
     r"<sha>\s+.*<sha>"),
    ("C7", "a masked date on the line", False,
     r"<date>"),
    ("C8", "a sha followed by a digit column", False,
     r"^(?:HEAD:\s*)?[A-Za-z ]{0,16}<sha>\s+\d"),
    # --- bad on purpose.  B1 and B2 are the two that the OUT column cannot see. ---------
    ("B1", "a `FINDING: <sha>` sentence", True,
     r"^\s*(?:\*\*\* )?FINDING: <sha>"),
    ("B2", "a `P<n> predicted / got` row", True,
     r"^\s*P\d+[a-z]?\s+predicted\b"),
    ("B3", "an `A<n> TOTAL BAD:` counter", True,
     r"^\s*A\d+ TOTAL BAD:"),
    ("B4", "the bare-subject rule, case-blind", True,
     r"(?i)^\s*[a-z][a-z0-9_]*(?:[+/][a-z0-9_]+)*:\s+\S"),
    ("B5", "any line quoting a sha at all", True,
     r"<sha>"),
]


def candidate(pattern):
    """A candidate widening as a predicate.  A widening cannot LOSE hits — it is the shipped
    rule OR the candidate — so the columns below are deltas of a superset and never a swap.
    That is a property of how the battery is composed, and it is why `gained` is subtraction.
    """
    rx = re.compile(pattern)
    return lambda line: bool(is_walk_line(line) or rx.search(line))


