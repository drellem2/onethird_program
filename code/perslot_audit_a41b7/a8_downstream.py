    check("%s n=%d no negative atom" % (label, n), all(w > 0 for w in mu.values()))
    check("%s n=%d every flip <= 1/3" % (label, n),
          all(v <= F(1, 3) for v in rep["flips"].values()),
          "max %s" % max(rep["flips"].values()))
    cflip = [p for p in C if rep["flips"][p] != 0]
    check("%s n=%d comparable pairs all at flip 0" % (label, n), cflip == [], str(cflip[:4]))
    viol = [z for z in rep["slot_violations"] if (z[1], z[2]) in I]
    check("%s n=%d per-slot symmetry holds on every incomparable pair" % (label, n),
          viol == [], str(viol[:3]))
    check("%s n=%d the comparable set is transitively closed (a real poset)" % (label, n),
          closure(n, C) == frozenset(C))
    if expect is not None:
        check("%s n=%d E[inv] = %s as claimed" % (label, n, expect), rep["einv"] == expect,
              "mine %s claimed %s" % (rep["einv"], expect))
    print("      -> MY E[inv] = %-10s  eps_spec = %-10s   (n-1)/3 = %-8s  %s"
          % (rep["einv"], L.eps_spec(n, rep["einv"]), F(n - 1, 3),
             "BEATS (n-1)/3" if rep["einv"] > F(n - 1, 3) else "does not beat (n-1)/3"))
    return rep["einv"]


