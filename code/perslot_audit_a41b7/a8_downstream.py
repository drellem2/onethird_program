def closure(n, C):
    C = set(C)
    changed = True
    while changed:
        changed = False
        for (a, b) in list(C):
            for (c, d) in list(C):
                if b == c and (a, d) not in C:
                    C.add((a, d)); changed = True
    return frozenset(C)


def verify(n, I, mu, label, expect=None):
    """MY checker.  Returns E[inv].  Shares no line with lp200d.measure_report."""
